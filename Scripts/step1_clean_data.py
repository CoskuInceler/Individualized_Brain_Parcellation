"""
STEP 1: CLEAN AND CONSOLIDATE DATA
====================================
This is the first script you run in the pipeline. It takes your raw
fMRI data and prepares it for all parcellation methods.

What it does:
    1. (Optional) Test mode: Checks that all input files exist and can be
       loaded before committing to the full cleaning run. Use this first
       to make sure your folder structure is correct.

    2. Clean each run: For every subject × run combination, applies:
       - Confound regression (motion + WM + CSF regressors)
       - Bandpass filtering (0.01–0.10 Hz)
       - Linear detrending
       - Z-score normalization

    3. Consolidate: Concatenates cleaned runs into sessions and an ALL
       combination so that downstream methods have maximum data available.

Output files:
    Per-run:     Outputs/Shared_Cleaned/{subj}_{run}_clean.npy / .dtseries.nii
    Per-session: Outputs/Shared_Cleaned/Aggregated/{subj}_REST1_Dense.npy / .dtseries.nii
                 Outputs/Shared_Cleaned/Aggregated/{subj}_REST2_Dense.npy / .dtseries.nii
    All runs:    Outputs/Shared_Cleaned/Aggregated/{subj}_ALL_Dense.npy   / .dtseries.nii

Usage:
    python step1_clean_data.py          # Full clean + consolidate
    python step1_clean_data.py --test   # Just check that files exist and load
"""

import os
import sys
import numpy as np
import pandas as pd
import nibabel as nib
from nibabel import cifti2
from nilearn import signal
import config


# =============================================================================
# CLEANING SETTINGS
# =============================================================================
# These parameters control the preprocessing applied to every run.
# They are standard choices for HCP resting-state fMRI.

TR = 0.72                       # Repetition time (seconds) — HCP standard
HIGH_PASS = 0.01                # Remove ultra-slow drifts below 0.01 Hz
LOW_PASS = 0.10                 # Remove fast noise above 0.10 Hz
DETREND = True                  # Remove linear trends before filtering
STANDARDIZE = "zscore_sample"   # Z-score each vertex's time series


# =============================================================================
# TEST MODE (formerly step1_load_data.py)
# =============================================================================
